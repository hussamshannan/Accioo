export const DEFAULT_THEME_ID = "default";

// Ordered list of themes for rendering pickers.
export const THEME_LIST = Object.values(THEMES);

// Valid theme ids (used client-side and mirrored by the server allowlist).
export const THEME_IDS = Object.keys(THEMES);

export function isValidThemeId(id) {
  return Object.prototype.hasOwnProperty.call(THEMES, id);
}

// Resolve the full CSS-var map for a theme + mode, merged over the default
// variant so partial themes still cover every variable.
export function resolveThemeVars(themeId, dark) {
  const variant = dark ? "dark" : "light";
  const theme = THEMES[themeId] || THEMES[DEFAULT_THEME_ID];
  return { ...THEMES[DEFAULT_THEME_ID][variant], ...theme[variant] };
}
